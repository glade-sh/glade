import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { test } from "node:test";

const root = fileURLToPath(new URL("../../", import.meta.url));
test("embedded update installer matches the maintained installer", async () => {
  const installer = await readFile(`${root}/site/install.sh`, "utf8");
  const embedded = await readFile(`${root}/internal/gladecli/update_installer.sh`, "utf8");
  assert.equal(embedded, installer.replace("#!/usr/bin/env sh\n", "#!/usr/bin/env sh\n# Code generated by go generate; DO NOT EDIT.\n"));
});
