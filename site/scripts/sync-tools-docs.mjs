import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const siteRoot = path.resolve(scriptDir, "..");
const repoRoot = path.resolve(siteRoot, "..");
const toolsRoot = process.env.GLADE_TOOLS_DIR
  ? path.resolve(process.env.GLADE_TOOLS_DIR)
  : path.resolve(repoRoot, "..", "glade-tools");
const outDir = path.join(siteRoot, "docs-src", "maintainer", "tools");
const check = process.argv.includes("--check");

const docs = [
  { source: "README.md", target: "README.md" },
  { source: "docs/plugin-registry.md", target: "plugin-registry.md" },
  { source: "docs/CAPABILITY_WORK_QUEUE.md", target: "capability-work-queue.md" },
  { source: "docs/visualforce-oracle.md", target: "visualforce-oracle.md" },
  { source: "docs/reports/lwc-shell-oracle-support.md", target: "lwc-shell-oracle-support.md" }
];

const routeBySource = new Map([
  ["README.md", "/maintainer/tools/"],
  ["docs/plugin-registry.md", "/maintainer/tools/plugin-registry"],
  ["docs/CAPABILITY_WORK_QUEUE.md", "/maintainer/tools/capability-work-queue"],
  ["docs/visualforce-oracle.md", "/maintainer/tools/visualforce-oracle"],
  ["docs/reports/lwc-shell-oracle-support.md", "/maintainer/tools/lwc-shell-oracle-support"]
]);

function normalizeMarkdown(input, source) {
  let markdown = input.replace(/\r\n/g, "\n").trimEnd();
  markdown = rewriteHeading(markdown);
  markdown = rewriteSyncedLinks(markdown);
  return [
    "<!-- Generated by site/scripts/sync-tools-docs.mjs. Do not edit. -->",
    "",
    `> Source: \`glade-tools/${source}\`.`,
    "",
    markdown,
    ""
  ].join("\n");
}

function rewriteHeading(markdown) {
  return markdown.replace(/^#\s+(.+)$/m, (_, heading) => {
    if (heading.startsWith("glade-tools:")) return `# ${heading}`;
    return `# glade-tools: ${heading}`;
  });
}

function rewriteSyncedLinks(markdown) {
  return markdown.replace(/\]\(([^)]+\.md)\)/g, (match, link) => {
    const normalized = link.replace(/^\.\//, "");
    const route = routeBySource.get(normalized);
    if (!route) return `](https://github.com/glade-sh/glade-tools/blob/main/${encodeURI(normalized)})`;
    return `](${route})`;
  });
}

async function main() {
  const generated = [];
  for (const doc of docs) {
    const sourcePath = path.join(toolsRoot, doc.source);
    const targetPath = path.join(outDir, doc.target);
    const sourceText = await readFile(sourcePath, "utf8");
    generated.push({
      ...doc,
      targetPath,
      content: normalizeMarkdown(sourceText, doc.source)
    });
  }

  if (check) {
    const drift = [];
    for (const doc of generated) {
      const current = await readFile(doc.targetPath, "utf8").catch(() => "");
      if (current !== doc.content) drift.push(path.relative(siteRoot, doc.targetPath));
    }
    if (drift.length > 0) {
      console.error(`Synced glade-tools docs are out of date:\n${drift.map((item) => `- ${item}`).join("\n")}`);
      console.error("Run `npm run sync:tools-docs --prefix site`.");
      process.exit(1);
    }
    return;
  }

  await mkdir(outDir, { recursive: true });
  await Promise.all(generated.map((doc) => writeFile(doc.targetPath, doc.content)));
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
