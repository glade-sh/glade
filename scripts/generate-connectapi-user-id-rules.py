#!/usr/bin/env python3
"""Generate captured ConnectApi User-ID checks from the checked-in native rows."""
import csv
import json
import re
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parent.parent
shape = json.loads((root / 'testdata/generated/connectapi_shape.json').read_text())
types = {item['name'].lower(): item for item in shape['types']}
rules = {}
with (root / 'internal/apextest/testdata/conformance/capi2_arguments/org.tsv').open() as f:
    for row in csv.DictReader(f, delimiter='\t'):
        match = re.fullmatch(r'all\.([^.]+)\.([^\(]+)\((.*)\)', row['case'])
        found = re.search(r"parameter: '([^']+)'", row['result'])
        if not match or not found:
            raise ValueError(row['case'])
        cls, method, signature = match.groups()
        param_name = found.group(1)
        args = signature.split(',') if signature else []
        candidates = [m for m in types[cls.lower()]['staticMethods']
                      if m['name'].lower() == method.lower() and
                      [p['type'].replace('System.', '').lower() for p in m['params']] ==
                      [p.replace('System.', '').lower() for p in args]]
        if len(candidates) != 1:
            raise ValueError('ambiguous overload: ' + row['case'])
        positions = [i for i, p in enumerate(candidates[0]['params']) if p['name'].lower() == param_name.lower()]
        if len(positions) != 1:
            raise ValueError('ambiguous parameter: ' + row['case'])
        key = ('connectapi.' + cls + '.' + method + '(' + signature + ')').lower().replace('system.', '').replace(' ', '')
        value = (positions[0], param_name)
        if key in rules and rules[key] != value:
            raise ValueError('conflicting native rows: ' + key)
        rules[key] = value
out = '// Code generated by scripts/generate-connectapi-user-id-rules.py; DO NOT EDIT.\npackage vm\n\n'
out += '// connectAPIUserIDRule records User ID rejection in capi2_arguments/org.tsv.\nfunc connectAPIUserIDRule(key string) (connectAPIArgumentRule, bool) {\n switch key {\n'
for key, (position, name) in sorted(rules.items()):
    out += f'case "{key}": return connectAPIArgumentRule{{index: {position}, param: "{name}"}}, true\n'
out += '}\n return connectAPIArgumentRule{}, false\n}\n'
dest = root / 'internal/vm/platform_connectapi_user_id_rules.go'
dest.write_text(out)
subprocess.run(['gofmt', '-w', str(dest)], check=True)
print('generated', len(rules), 'overload rules')
