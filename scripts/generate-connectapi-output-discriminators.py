#!/usr/bin/env python3
"""Generate ConnectApi JSON discriminators from native capture."""
import csv
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parent.parent
rows = {}
with (root / 'internal/apextest/testdata/conformance/capi2_output_subtypes/org.tsv').open() as f:
    for row in csv.DictReader(f, delimiter='\t'):
        name, value = row['case'].lower(), row['result']
        if value == 'null' or value.startswith('EX:'):
            continue
        if name in rows and rows[name] != value:
            raise ValueError('version-specific discriminator needs explicit ranges: ' + name)
        rows[name] = value
out = '// Code generated by scripts/generate-connectapi-output-discriminators.py; DO NOT EDIT.\npackage vm\n\nimport "strings"\n\n'
out += 'func connectAPIOutputDiscriminator(typeName string) (string, bool) {\n switch strings.ToLower(typeName) {\n'
for name, value in sorted(rows.items()):
    out += f'case "{name}": return "{value}", true\n'
out += '}\n return "", false\n}\n'
assigned = set()
with (root / 'internal/apextest/testdata/conformance/capi2_assigned_outputs/org.tsv').open() as f:
    for row in csv.DictReader(f, delimiter='\t'):
        name = 'connectapi.' + row['case'].lower()
        if row['api'] == '67.0' and row['result'].startswith('JSON='):
            serialized = row['result'].split('|', 1)[0].removeprefix('JSON=')
            if serialized == rows.get(name):
                assigned.add(name)
# The separate segment capture records an assigned enum boundary.
assigned.update('connectapi.' + name + 'segment' for name in (
    'entitylink', 'fieldchangename', 'fieldchangevalue', 'hashtag', 'inlineimage', 'link',
    'markupbegin', 'markupend', 'mention', 'morechanges', 'resourcelink', 'text'))
out += 'func connectAPIOverrideAssignedDiscriminator(typeName string) bool {\n switch strings.ToLower(typeName) {\n'
for name in sorted(assigned):
    out += f'case "{name}": return true\n'
out += '}\n return false\n}\n'
dest = root / 'internal/vm/platform_connectapi_output_discriminators.go'
dest.write_text(out)
subprocess.run(['gofmt', '-w', str(dest)], check=True)
print('generated', len(rows), 'output discriminators')
