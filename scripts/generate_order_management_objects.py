#!/usr/bin/env python3
"""Generate the native-backed order-management object availability list."""
import csv
from pathlib import Path
root = Path(__file__).resolve().parents[1]
source = root / 'internal/apextest/testdata/conformance/org_commerce_family/org.tsv'
with source.open(newline='') as f:
    names = sorted(row['object'] for row in csv.DictReader(f, delimiter='\t'))
out = ['// Code generated by scripts/generate_order_management_objects.py; DO NOT EDIT.', '', 'package storage', '', 'var orderManagementObjectNames = []string{']
out += [f'\t"{name}",' for name in names]
out += ['}', '', 'var orderManagementObjectLookup = map[string]struct{}{']
out += [f'\t"{name.lower()}": {{}},' for name in names]
out += ['}', '']
(root / 'internal/storage/order_management_objects_generated.go').write_text('\n'.join(out))

source_b2b = root / 'internal/apextest/testdata/conformance/org_commerce_b2b/org.tsv'
with source_b2b.open(newline='') as f:
    rows = list(csv.DictReader(f, delimiter='\t'))
for label, value in [('b2bAvailable', '111'), ('b2bUnavailable', '00Q')]:
    selected = sorted(row['object'] for row in rows if all(row[k] == value for k in ('62anon', '62test', '67anon', '67test')))
    out = ['// Code generated by scripts/generate_order_management_objects.py; DO NOT EDIT.', '', 'package storage', '', f'var {label}ObjectNames = []string{{']
    out += [f'\t"{name}",' for name in selected]
    out += ['}', '', f'var {label}ObjectLookup = map[string]struct{{}}{{']
    out += [f'\t"{name.lower()}": {{}},' for name in selected]
    out += ['}', '']
    (root / f'internal/storage/{label.lower()}_objects_generated.go').write_text('\n'.join(out))

community = root / 'internal/apextest/testdata/conformance/org_community_family/org.tsv'
with community.open(newline='') as f:
    names = sorted(row['object'] for row in csv.DictReader(f, delimiter='\t'))
history = root / 'internal/apextest/testdata/conformance/org_community_history/org.tsv'
with history.open(newline='') as f:
    names = sorted(set(names) | {row['object'] for row in csv.DictReader(f, delimiter='\t')})
out = ['// Code generated by scripts/generate_order_management_objects.py; DO NOT EDIT.', '', 'package storage', '', 'var networkSettingObjectNames = []string{']
out += [f'\t"{name}",' for name in names]
out += ['}', '', 'var networkSettingObjectLookup = map[string]struct{}{']
out += [f'\t"{name.lower()}": {{}},' for name in names]
out += ['}', '']
(root / 'internal/storage/network_setting_objects_generated.go').write_text('\n'.join(out))

# Plain Developer global describe (plain_global_describe): bit 1 anonymous 62.0,
# 2 anonymous 67.0, 4 isTest-only 62.0, 8 isTest-only 67.0.
plain = root / 'internal/apextest/testdata/conformance/plain_global_describe'
bits = {}
for name, bit in [('keys-anonymous-62.txt', 1), ('keys-anonymous-67.txt', 2), ('keys-test-only-62.txt', 4), ('keys-test-only-67.txt', 8)]:
    for key in (plain / name).read_text().split():
        bits[key] = bits.get(key, 0) | bit
out = ['// Code generated by scripts/generate_order_management_objects.py; DO NOT EDIT.', '', 'package storage', '', 'var plainDeveloperObjectLookup = map[string]uint8{']
out += [f'\t"{key}": {bits[key]},' for key in sorted(bits)]
out += ['}', '']
(root / 'internal/storage/plain_developer_objects_generated.go').write_text('\n'.join(out))
