#!/usr/bin/env python3
"""Generate overload-specific accepted prefixes from native capture."""
import csv,json,re,subprocess
from pathlib import Path
root=Path(__file__).resolve().parent.parent
folder=root/'internal/apextest/testdata/conformance/capi2_argument_prefixes'
prefixes=json.loads((folder/'prefixes.json').read_text())
if '000' not in prefixes:prefixes.append('000')
entries={}
with (folder/'org.tsv').open() as f:
 for row in csv.DictReader(f,delimiter='\t'):
  m=re.fullmatch(r'all\.([^.]+)\.([^\(]+)\((.*)\)',row['case']);assert m
  cls,method,args=m.groups();key=('connectapi.'+cls+'.'+method+'('+args+')').lower().replace('system.','').replace(' ','')
  vals=row['accepted-prefixes']
  if key in entries and entries[key]!=vals:raise ValueError('version-specific prefixes: '+key)
  entries[key]=vals
out='// Code generated by scripts/generate-connectapi-prefix-rules.py; DO NOT EDIT.\npackage vm\n\n'
out+='const connectAPITestedIDPrefixes = "|'+ '|'.join(sorted(prefixes))+'|"\n\n'
out+='func connectAPIAcceptedPrefixes(key string) (string, bool) {\n switch key {\n'
for key,vals in sorted(entries.items()):
 if len(vals.split(',')) > 100: vals='*'
 else: vals='|'+vals.replace(',','|')+'|' if vals else ''
 out+=f'case "{key}": return "{vals}", true\n'
out+='}\n return "", false\n}\n'
dest=root/'internal/vm/platform_connectapi_prefix_rules.go';dest.write_text(out);subprocess.run(['gofmt','-w',str(dest)],check=True);print('generated',len(entries),'prefix rules')
