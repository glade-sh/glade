#!/usr/bin/env python3
"""Generate deployment admission data from the captured list-view rows."""
import csv
from pathlib import Path

here = Path(__file__).resolve().parent
sources = [here / 'testdata/pr163_list_shapes/org.tsv',
           here / 'testdata/pr163_list_custom_shapes/org.tsv']
rows = []
for source in sources:
    with source.open(newline='') as f:
        for row in csv.DictReader(f, delimiter='\t'):
            if row['route'] == 'deploy' and row['api'] in ('59.0', '67.0'):
                rows.append(row)


# This capture is explicitly the Account deployment route, not UI metadata.
with (here / 'testdata/pr163_list_columns/org.tsv').open(newline='') as f:
    for row in csv.DictReader(f, delimiter='\t'):
        if row['route'] == 'deploy' and row['api'] in ('59.0', '67.0') and '.' not in row['column']:
            rows.append(dict(row, object='Account'))

# Treat custom object names only as independent observations of the same
# explicitly captured text-name/no-fields shape; never emit the names.
custom = {}
standard = {}
for row in rows:
    key = (row['api'], row['column'])
    result = row['result']
    if result not in ('accepted', 'rejected'):
        raise ValueError(f'unexpected capture outcome: {row}')
    if row['object'].endswith('__c'):
        custom.setdefault(key, {})[row['object']] = result
    else:
        standard_key = (row['api'], row['object'], row['column'])
        if standard_key in standard and standard[standard_key] != result:
            raise ValueError(f'conflicting observations: {standard_key}')
        standard[standard_key] = result
for key, observations in custom.items():
    if len(observations) < 2 or len(set(observations.values())) != 1:
        raise ValueError(f'custom-shape observations disagree or are incomplete: {key}')
    standard[(key[0], '', key[1])] = next(iter(observations.values()))

out = ['// Code generated by generate_list_view_catalog.py; DO NOT EDIT.',
       '', 'package server', '',
       '// An empty object denotes the captured ordinary text-name custom shape.',
       'var listViewColumnNativeCatalog = map[listViewColumnCatalogKey]bool{']
for (api, obj, column), result in sorted(standard.items()):
    out.append(f'\t{{{api!r}, {obj!r}, {column!r}}}: {str(result == "accepted").lower()},'.replace("'", '"'))
out += ['}', '']
(here / 'list_view_catalog_generated.go').write_text('\n'.join(out))
