const standardDescribeScalarsGeneratedFile = "standard_describe_scalars_generated.go"

// Every pack member's keyPrefix and triggerable must match the generated
// scalar table, in index order. A regenerated pack fails here until the table
// is regenerated with GLADE_UPDATE_DESCRIBE_SCALARS=1.
func TestStandardDescribeCatalogV2ScalarsMatchPack(t *testing.T) {
	want := make([]standardDescribeCatalogV2Scalar, 0, len(standardDescribeCatalogV2Index))
	for _, indexEntry := range standardDescribeCatalogV2Index {
		describe, err := decodeStandardDescribeCatalogV2Member(standardDescribeCatalogV2Pack, indexEntry)
		if err != nil {
			t.Fatal(err)
		}
		scalar := standardDescribeCatalogV2Scalar{Name: indexEntry.Name, Facets: standardDescribeScalarFacetsOf(describe)}
		if describe.KeyPrefix != nil {
			scalar.KeyPrefix = *describe.KeyPrefix
		}
		want = append(want, scalar)
	}
	if os.Getenv("GLADE_UPDATE_DESCRIBE_SCALARS") == "1" {
		writeStandardDescribeScalarsGenerated(t, want)
	}
	got := standardDescribeCatalogV2Scalars[:]
	if len(got) != len(want) {
		t.Fatalf("scalar table has %d entries, pack has %d; regenerate with GLADE_UPDATE_DESCRIBE_SCALARS=1", len(got), len(want))
	}
	for position := range want {
		if got[position] != want[position] {
			t.Fatalf("scalar table entry %d = %+v, pack member = %+v; regenerate with GLADE_UPDATE_DESCRIBE_SCALARS=1", position, got[position], want[position])
		}
		lookedUp, ok := lookupStandardDescribeCatalogV2Scalar(standardDescribeCatalogV2Index[position])
		if !ok {
			t.Fatalf("%s: scalar lookup missed its own table entry", want[position].Name)
		}
		member, err := decodeStandardDescribeCatalogV2Member(standardDescribeCatalogV2Pack, standardDescribeCatalogV2Index[position])
		if err != nil {
			t.Fatal(err)
		}
		fromMember := standardDescribeObject{KeyPrefix: member.KeyPrefix, Triggerable: member.Triggerable}
		if !reflect.DeepEqual(lookedUp, fromMember) {
			t.Fatalf("%s: scalar lookup = %+v, member = %+v", want[position].Name, lookedUp, fromMember)
		}
	}
}

func writeStandardDescribeScalarsGenerated(t *testing.T, scalars []standardDescribeCatalogV2Scalar) {
	t.Helper()
	var out bytes.Buffer
	out.WriteString("// Code generated by standard_describe_scalars_test.go from standard_describe_catalog_v2.pack; DO NOT EDIT.\n")
	out.WriteString("// Regenerate: GLADE_UPDATE_DESCRIBE_SCALARS=1 go test ./internal/storage -run TestStandardDescribeCatalogV2ScalarsMatchPack\n\n")
	out.WriteString("package storage\n\n")
	out.WriteString("// standardDescribeCatalogV2Scalars holds keyPrefix and triggerable for every\n")
	out.WriteString("// V2 pack member, in index order.\n")
	fmt.Fprintf(&out, "var standardDescribeCatalogV2Scalars = [%d]standardDescribeCatalogV2Scalar{\n", len(scalars))
	for _, scalar := range scalars {
		fmt.Fprintf(&out, "\t{%q, %q, %d},\n", scalar.Name, scalar.KeyPrefix, scalar.Facets)
	}
	out.WriteString("}\n")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		t.Fatalf("format generated scalar table: %v", err)
	}
	if err := os.WriteFile(filepath.Join(".", standardDescribeScalarsGeneratedFile), formatted, 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("wrote %s with %d entries", standardDescribeScalarsGeneratedFile, len(scalars))
}

// A scalar lookup followed by a full lookup decodes the production member
// once: the scalars come from the generated table and the full lookup pays
// the only gunzip and decode. Before the table, scalar-first cost two decodes
// per object during org setup (v0.3.4 startup regression).
func TestStandardDescribeCatalogV2ScalarThenFullDecodesOnce(t *testing.T) {
	for _, name := range []string{"Account", "Contact", "Opportunity", "CareProgram", "Lead"} {
		t.Run(name, func(t *testing.T) {
			var decodes atomic.Int64
			cache := newStandardDescribeCatalogV2RawCache(func(entry standardDescribeCatalogV2IndexEntry) (standardDescribeObject, error) {
				decodes.Add(1)
				return decodeStandardDescribeCatalogV2Member(standardDescribeCatalogV2Pack, entry)
			})
			cache.scalarOnly = true
			cache.scalars = lookupStandardDescribeCatalogV2Scalar

			scalar, found, err := cache.scalarForName(name)
			if err != nil || !found {
				t.Fatalf("scalar lookup: found=%v err=%v", found, err)
			}
			if got := decodes.Load(); got != 0 {
				t.Fatalf("scalar lookup decoded %d members, want 0", got)
			}
			full, found, err := cache.entryForName(name)
			if err != nil || !found || len(full.Fields) == 0 {
				t.Fatalf("full lookup: found=%v err=%v fields=%d", found, err, len(full.Fields))
			}
			if got := decodes.Load(); got != 1 {
				t.Fatalf("scalar then full lookup decoded %d members, want 1", got)
			}
			if scalar.KeyPrefix == nil || full.KeyPrefix == nil || *scalar.KeyPrefix != *full.KeyPrefix {
				t.Fatalf("keyPrefix scalar=%v full=%v", scalar.KeyPrefix, full.KeyPrefix)
			}
			if (scalar.Triggerable == nil) != (full.Triggerable == nil) || (scalar.Triggerable != nil && *scalar.Triggerable != *full.Triggerable) {
				t.Fatalf("triggerable scalar=%v full=%v", scalar.Triggerable, full.Triggerable)
			}
			// The full value must match an independent decode exactly; the
			// table only supplies pointers that carry the same values.
			independent, err := decodeStandardDescribeCatalogV2Member(standardDescribeCatalogV2Pack, cacheIndexEntry(t, name))
			if err != nil || !reflect.DeepEqual(full, independent) {
				t.Fatalf("full lookup after scalar differs from a direct decode: %v", err)
			}
		})
	}
}

func cacheIndexEntry(t *testing.T, name string) standardDescribeCatalogV2IndexEntry {
	t.Helper()
	entry, ok := lookupStandardDescribeCatalogV2Index(standardDescribeCatalogV2Index, name)
	if !ok {
		t.Fatalf("%s missing from the V2 index", name)
	}
	return entry
}

// The exported scalar readers must not decode a production member.
func TestStandardObjectScalarReadersDoNotDecodeProductionMembers(t *testing.T) {
	previous := standardDescribeCatalogV2RawProductionCache
	t.Cleanup(func() { standardDescribeCatalogV2RawProductionCache = previous })
	var decodes atomic.Int64
	cache := newStandardDescribeCatalogV2RawCache(func(entry standardDescribeCatalogV2IndexEntry) (standardDescribeObject, error) {
		decodes.Add(1)
		return decodeStandardDescribeCatalogV2Member(standardDescribeCatalogV2Pack, entry)
	})
	cache.scalarOnly = true
	cache.scalars = lookupStandardDescribeCatalogV2Scalar
	standardDescribeCatalogV2RawProductionCache = cache

	for _, name := range []string{"Account", "Case", "Task", "Event", "User"} {
		standardObjectTriggerableCache.Delete(name)
		t.Cleanup(func() { standardObjectTriggerableCache.Delete(name) })
		prefix, known := StandardObjectDescribeKeyPrefix(name)
		if !known || prefix == nil || len(*prefix) != 3 {
			t.Fatalf("%s: keyPrefix=%v known=%v", name, prefix, known)
		}
		if _, known := StandardObjectTriggerable(name); !known {
			t.Fatalf("%s: triggerable unknown", name)
		}
	}
	if got := decodes.Load(); got != 0 {
		t.Fatalf("scalar readers decoded %d members, want 0", got)
	}
}

// BenchmarkStandardDescribeScalarThenFullCold measures the org-setup pattern
// (key prefix first, field graph second) on a fresh cache.
func BenchmarkStandardDescribeScalarThenFullCold(b *testing.B) {
	b.ReportAllocs()
	for index := 0; index < b.N; index++ {
		cache := newStandardDescribeCatalogV2RawCache(func(entry standardDescribeCatalogV2IndexEntry) (standardDescribeObject, error) {
			return decodeStandardDescribeCatalogV2Member(standardDescribeCatalogV2Pack, entry)
		})
		cache.scalarOnly = true
		cache.scalars = lookupStandardDescribeCatalogV2Scalar
		if _, ok, err := cache.scalarForName("Account"); err != nil || !ok {
			b.Fatalf("scalar Account: ok=%v err=%v", ok, err)
		}
		if full, ok, err := cache.entryForName("Account"); err != nil || !ok || len(full.Fields) == 0 {
			b.Fatalf("full Account: ok=%v err=%v", ok, err)
		}
	}
}
