package storage

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"testing"
)

// spreadCoreScanPackages are the packages that read or write standard objects
// by name on the way to a test run. A catalog object whose name appears as a
// string literal in their hand-written code is installed with every lazy org,
// because that code reads org.Objects[literal] directly.
var spreadCoreScanPackages = []string{
	"storage", "vm", "dml", "soql", "resource", "automation", "apextest", "sobject",
	"profile", "startupcache", "sema", "server", "dbmanager", "visualforce", "testdaemon",
}

func scanSpreadCoreLiterals(t *testing.T) []string {
	t.Helper()
	known := make(map[string]bool)
	for _, name := range KnownStandardObjectNames() {
		known[name] = true
	}
	found := make(map[string]bool)
	for _, pkg := range spreadCoreScanPackages {
		files, err := filepath.Glob(filepath.Join("..", pkg, "*.go"))
		if err != nil {
			t.Fatal(err)
		}
		for _, file := range files {
			if strings.HasSuffix(file, "_test.go") {
				continue
			}
			data, err := os.ReadFile(file)
			if err != nil {
				t.Fatal(err)
			}
			if bytes.Contains(data[:min(len(data), 400)], []byte("Code generated")) {
				continue
			}
			parsed, err := parser.ParseFile(token.NewFileSet(), file, data, 0)
			if err != nil {
				t.Fatal(err)
			}
			// Picklist entries are values, not object lookups, even when a
			// value coincides with a standard object name.
			picklistValues := make(map[*ast.BasicLit]bool)
			for _, decl := range parsed.Decls {
				fn, ok := decl.(*ast.FuncDecl)
				if !ok || fn.Name.Name != "plainDeveloperPicklist" {
					continue
				}
				ast.Inspect(fn.Body, func(n ast.Node) bool {
					assign, ok := n.(*ast.AssignStmt)
					if !ok || len(assign.Lhs) != 1 || len(assign.Rhs) != 1 {
						return true
					}
					name, ok := assign.Lhs[0].(*ast.Ident)
					if !ok || name.Name != "entries" {
						return true
					}
					if values, ok := assign.Rhs[0].(*ast.CompositeLit); ok {
						for _, value := range values.Elts {
							if lit, ok := value.(*ast.BasicLit); ok {
								picklistValues[lit] = true
							}
						}
					}
					return true
				})
			}
			local := make(map[string]bool)
			ast.Inspect(parsed, func(n ast.Node) bool {
				if lit, ok := n.(*ast.BasicLit); ok && lit.Kind == token.STRING {
					if picklistValues[lit] {
						return true
					}
					if s, err := strconv.Unquote(lit.Value); err == nil && known[s] {
						local[s] = true
					}
				}
				return true
			})
			// A file that names a large part of the catalog is data, not code.
			if len(local) > 150 {
				continue
			}
			for name := range local {
				found[name] = true
			}
		}
	}
	names := make([]string, 0, len(found))
	for name := range found {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

// The core list must name every catalog object that hand-written code refers
// to by literal. Regenerate it with GLADE_UPDATE_SPREAD_CORE=1.
func TestStandardSpreadCoreCoversLiteralReferences(t *testing.T) {
	want := scanSpreadCoreLiterals(t)
	if os.Getenv("GLADE_UPDATE_SPREAD_CORE") != "" {
		var out bytes.Buffer
		out.WriteString("// Code generated by TestStandardSpreadCoreCoversLiteralReferences with GLADE_UPDATE_SPREAD_CORE=1; DO NOT EDIT.\n\npackage storage\n\n")
		out.WriteString("// standardSpreadCoreObjects are the catalog objects a source-backed lazy org installs up front.\n")
		out.WriteString("var standardSpreadCoreObjects = []string{\n")
		for _, name := range want {
			fmt.Fprintf(&out, "\t%q,\n", name)
		}
		out.WriteString("}\n")
		if err := os.WriteFile("standard_spread_core_generated.go", out.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	have := make(map[string]bool, len(standardSpreadCoreObjects))
	for _, name := range standardSpreadCoreObjects {
		have[name] = true
	}
	var missing []string
	for _, name := range want {
		if !have[name] {
			missing = append(missing, name)
		}
	}
	if len(missing) > 0 {
		t.Fatalf("standardSpreadCoreObjects lacks %d literal-referenced objects (run with GLADE_UPDATE_SPREAD_CORE=1): %v", len(missing), missing)
	}
}
