package storage

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"reflect"
	"testing"
)

const standardChildRelationshipsGeneratedFile = "standard_child_relationships_generated.go"

// The generated child-relationship table must equal the catalog walk, entry
// for entry and in order. A regenerated pack or stub overlay fails here until
// the table is regenerated with GLADE_UPDATE_CHILD_RELATIONSHIPS=1.
func TestStandardChildRelationshipsMatchCatalog(t *testing.T) {
	want := standardChildRelationshipsFromCatalog()
	if os.Getenv("GLADE_UPDATE_CHILD_RELATIONSHIPS") == "1" {
		writeStandardChildRelationshipsGenerated(t, want)
	}
	got := StandardChildRelationships()
	if len(got) != len(want) {
		t.Fatalf("child relationship table has %d entries, catalog walk has %d; regenerate with GLADE_UPDATE_CHILD_RELATIONSHIPS=1", len(got), len(want))
	}
	for position := range want {
		if !reflect.DeepEqual(got[position], want[position]) {
			t.Fatalf("child relationship table entry %d = %+v, catalog walk = %+v; regenerate with GLADE_UPDATE_CHILD_RELATIONSHIPS=1", position, got[position], want[position])
		}
	}
}

func writeStandardChildRelationshipsGenerated(t *testing.T, relationships []StandardChildRelationship) {
	t.Helper()
	var out bytes.Buffer
	out.WriteString("// Code generated by standard_child_relationships_test.go from the standard object catalog; DO NOT EDIT.\n")
	out.WriteString("// Regenerate: GLADE_UPDATE_CHILD_RELATIONSHIPS=1 go test ./internal/storage -run TestStandardChildRelationshipsMatchCatalog\n\n")
	out.WriteString("package storage\n\n")
	out.WriteString("// standardChildRelationshipTable holds every standard catalog child\n")
	out.WriteString("// relationship in catalog walk order (see standardChildRelationshipsFromCatalog).\n")
	fmt.Fprintf(&out, "var standardChildRelationshipTable = [%d]StandardChildRelationship{\n", len(relationships))
	for _, relationship := range relationships {
		fmt.Fprintf(&out, "\t{%q, %q, []string{", relationship.Child, relationship.Name)
		for i, parent := range relationship.Parents {
			if i > 0 {
				out.WriteString(", ")
			}
			fmt.Fprintf(&out, "%q", parent)
		}
		out.WriteString("}},\n")
	}
	out.WriteString("}\n")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		t.Fatalf("format generated child relationship table: %v", err)
	}
	if err := os.WriteFile(filepath.Join(".", standardChildRelationshipsGeneratedFile), formatted, 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("wrote %s with %d entries", standardChildRelationshipsGeneratedFile, len(relationships))
}
