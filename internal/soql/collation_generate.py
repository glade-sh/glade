 def root_items():
  for cp in range(0x110000):
   if 0xd800<=cp<=0xdfff:continue
   ce=c.elements(chr(cp))
   if icu.u_charType(cp) not in (0,17,18):
    status=icu.status();script=icu.uscript_getScript(cp,C.byref(status));icu.check(status)
    if script!=17:non_han.append(cp) # public USCRIPT_HAN value
   for x in ce:
    if x>>16:
     samples.setdefault(x>>16,cp);break
   yield cp,ce
 base=ranges(root_items())
