  manifest['profiles'][name]={'tag':tag,'caseFirst':case_first,'alternate':alternate,'variableTop':top>>16,'reorderUnits':len(reorder),'reorderConflicts':len(conflicts),'reorderExamples':conflicts[:8],'scalars':len(changed),'ranges':len(rs),'contractions':len(contraction),'sha256':hashlib.sha256((out/(name+'.json')).read_bytes()).hexdigest()}
  c.close();print(name,len(changed),'scalars',len(contraction),'contractions',len(conflicts),'lead-map conflicts',flush=True)
