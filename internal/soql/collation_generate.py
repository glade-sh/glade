"""Generate owned collation data through public Unicode/ICU interfaces.

No native observation is read by this generator. Root weights come from the
CLDR 46 archive. Tailored elements come from the public ICU 78.1 (CLDR 48)
collation-element iterator, UnicodeSet and sort-key APIs. ICU is generation
only: the Go runtime reads these UTF-8 text tables without linking ICU.

Usage: python3 collation_generate.py --cldr-archive CLDR46_CORE_ZIP
The ICU library must report exactly 78.1 and CLDR 48 for reproducibility.
"""
