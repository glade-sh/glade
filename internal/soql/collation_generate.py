def profile_name(tag):return tag.replace('@collation=','_').lower()
def ranges(items):
 """Lossless arithmetic runs; every point is observed before extending a run."""
 result=[];start=end=None;first=previous=step=None
 for cp,ce in items:
  ce=tuple(ce)
  if start is None:start=end=cp;first=previous=ce;step=None;continue
  delta=tuple(a-b for a,b in zip(ce,previous))
  if cp==end+1 and len(ce)==len(previous) and (step is None or step==delta):
   end=cp;previous=ce
   if step is None:step=delta
  else:
   result.append((start,end,first,step or (0,)*len(first)))
   start=end=cp;first=previous=ce;step=None
 if start is not None:result.append((start,end,first,step or (0,)*len(first)))
 return result

def serialize(rs,contractions,reorder=()):
 # Every generated byte is inspectable UTF-8 text, without scanner decoding.
 # Integer arrays preserve the exact lossless arithmetic-run representation.
 data={'format':'GLDC2','ranges':[{'first':a,'last':b,'elements':ce,'stride':step} for a,b,ce,step in rs],
       'contractions':[{'text':key,'elements':ce} for key,ce in sorted(contractions.items())],
       'reorder':list(reorder)}
 return (json.dumps(data,ensure_ascii=False,separators=(',',':')).replace('},{','},\n{')+'\n').encode('utf-8')

def write_data(path,data):
 path.write_bytes(data)


class ICU:
 def __init__(self,library,suffix):
  self.lib=C.CDLL(library);self.suffix=suffix
  def bind(name,ret,args):
   f=getattr(self.lib,name+suffix);f.restype=ret;f.argtypes=args;setattr(self,name,f)
  P=C.c_void_p;I=C.c_int32;U=C.c_uint32;S=C.c_int32;B=C.c_uint8
  for name,ret,args in [
   ('unorm2_getNFDInstance',P,[P]),('unorm2_normalize',I,[P,P,I,P,I,P]),('u_charType',C.c_int8,[I]),('uscript_getScript',I,[I,P]),('u_getVersion',None,[P]),('ulocdata_getCLDRVersion',None,[P,P]),
   ('ucol_open',P,[C.c_char_p,P]),('ucol_close',None,[P]),
   ('ucol_openElements',P,[P,P,I,P]),('ucol_closeElements',None,[P]),
   ('ucol_setText',None,[P,P,I,P]),('ucol_next',I,[P,P]),
   ('ucol_getSortKey',I,[P,P,I,P,I]),('ucol_getAttribute',I,[P,I,P]),
   ('ucol_getVariableTop',U,[P,P]),('ucol_getTailoredSet',P,[P,P]),
   ('ucol_getContractionsAndExpansions',None,[P,P,P,B,P]),
   ('ucol_getReorderCodes',I,[P,P,I,P]),('uset_openEmpty',P,[]),
   ('uset_close',None,[P]),('uset_getItemCount',I,[P]),
   ('uset_getItem',I,[P,I,P,P,P,I,P]),
  ]:bind(name,ret,args)
  version=(B*4)();self.u_getVersion(version);self.version=list(version)
  status=S(0);cldr=(B*4)();self.ulocdata_getCLDRVersion(cldr,C.byref(status));self.cldr=list(cldr)
  if self.version!=[78,1,0,0] or self.cldr!=[48,0,0,0]:raise RuntimeError(f'expected ICU 78.1 / CLDR 48, got {self.version} / {self.cldr}')
 def normalize(self,text):
  s=self.status();normalizer=self.unorm2_getNFDInstance(C.byref(s));self.check(s)
  raw=text.encode('utf-16-le');buf=(C.c_uint16*4096)()
  n=self.unorm2_normalize(normalizer,raw,len(raw)//2,buf,4096,C.byref(s));self.check(s)
  return bytes(buf)[:2*n].decode('utf-16-le')
 def status(self):return C.c_int32(0)
 def check(self,s):
  if s.value>0:raise RuntimeError('ICU status '+str(s.value))
 def set_items(self,u):
  scalars=[];strings=[]
  for i in range(self.uset_getItemCount(u)):
   a=C.c_int32();b=C.c_int32();buf=(C.c_uint16*512)();s=self.status()
   n=self.uset_getItem(u,i,C.byref(a),C.byref(b),buf,512,C.byref(s));self.check(s)
   if n:strings.append(bytes(buf)[:2*n].decode('utf-16-le'))
   else:scalars.extend(range(a.value,b.value+1))
  return scalars,strings

class Collator:
 def __init__(self,icu,tag):
  self.icu=icu;s=icu.status();self.c=icu.ucol_open(tag.encode(),C.byref(s));icu.check(s)
  s=icu.status();self.it=icu.ucol_openElements(self.c,b'',0,C.byref(s));icu.check(s)
 def close(self):self.icu.ucol_closeElements(self.it);self.icu.ucol_close(self.c)
 def elements(self,text):
  raw=text.encode('utf-16-le');s=self.icu.status();self.icu.ucol_setText(self.it,raw,len(raw)//2,C.byref(s));self.icu.check(s)
  out=[]
  while True:
   x=self.icu.ucol_next(self.it,C.byref(s))
   if x==-1:break
   if x:out.append(x&0xffffffff)
  self.icu.check(s);return tuple(out)
 def key(self,text):
  raw=text.encode('utf-16-le');buf=(C.c_uint8*1024)();n=self.icu.ucol_getSortKey(self.c,raw,len(raw)//2,buf,1024)
  if n>1024:raise RuntimeError('key buffer overflow')
  return bytes(buf[:n])
 def attr(self,n):s=self.icu.status();x=self.icu.ucol_getAttribute(self.c,n,C.byref(s));self.icu.check(s);return x
 def contractions(self):
  u=self.icu.uset_openEmpty();s=self.icu.status();self.icu.ucol_getContractionsAndExpansions(self.c,u,None,0,C.byref(s));self.icu.check(s)
  _,strings=self.icu.set_items(u);self.icu.uset_close(u);result={}
  for text in strings:
   text=self.icu.normalize(text)
   if len(text)>1:
    ce=self.elements(text)
    if text in result and result[text]!=ce:raise RuntimeError('inconsistent canonical contraction')
    result[text]=ce
  return result
 def tailored_scalars(self):
  s=self.icu.status();u=self.icu.ucol_getTailoredSet(self.c,C.byref(s));self.icu.check(s)
  scalars,_=self.icu.set_items(u);self.icu.uset_close(u);return sorted(set(scalars))

def main():
 p=argparse.ArgumentParser();p.add_argument('--cldr-archive');p.add_argument('--library',default='/usr/lib/libicucore.dylib');p.add_argument('--symbol-suffix',default='');p.add_argument('--output-dir',type=Path);p.add_argument('--check',action='store_true');args=p.parse_args()
