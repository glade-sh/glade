//go:build ignore

// Command collation_weights_generate derives the ASCII weight table for text
// collation from the captured single-character ordering in
// testdata/collation. Run it with go generate in this package.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"
)

func main() {
	values := map[string]rune{}
	data, err := os.ReadFile("testdata/collation/maps/T1-values.tsv")
	check(err)
	for _, line := range strings.Split(string(data), "\n")[1:] {
		cells := strings.Split(line, "\t")
		if len(cells) < 3 {
			continue
		}
		cp, err := strconv.ParseInt(strings.TrimPrefix(cells[1], "U+"), 16, 32)
		check(err)
		values[cells[0]] = rune(cp)
	}
	var ascending string
	data, err = os.ReadFile("testdata/collation/observations.tsv")
	check(err)
	for _, line := range strings.Split(string(data), "\n") {
		cells := strings.Split(line, "\t")
		if len(cells) < 6 || cells[0] != "t1" || cells[1] != "67.0" || cells[2] != "anonymous" || cells[3] != "first" {
			continue
		}
		for _, field := range strings.Split(cells[5], "|") {
			if strings.HasPrefix(field, "asc:") {
				ascending = strings.TrimPrefix(field, "asc:")
			}
		}
	}
	if ascending == "" {
		check(fmt.Errorf("no t1 ascending row"))
	}
	// Space is captured only inside strings; it sorts before every character
	// of the single-character row. Case pairs share a weight.
	const first = 64
	weights := [128]int{}
	assigned := [128]bool{}
	weights[' '], assigned[' '] = first, true
	next := first + 1
	for i := 0; i+2 <= len(ascending); i += 2 {
		r, ok := values[ascending[i:i+2]]
		if !ok || r >= 128 {
			check(fmt.Errorf("unexpected label %q", ascending[i:i+2]))
		}
		other := r
		if r >= 'a' && r <= 'z' {
			other = r - 32
		} else if r >= 'A' && r <= 'Z' {
			other = r + 32
		}
		if assigned[other] {
			weights[r], assigned[r] = weights[other], true
			continue
		}
		weights[r], assigned[r] = next, true
		next++
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by collation_weights_generate.go from testdata/collation; DO NOT EDIT.\n\npackage soql\n\n")
	out.WriteString("// asciiCollationWeight holds the captured weight of each ASCII character.\n// Characters absent from the capture (controls, DEL) sort below space in\n// code point order.\nvar asciiCollationWeight = [128]uint8{\n")
	for c := 0; c < 128; c++ {
		w := weights[c]
		if !assigned[c] {
			w = c
			if c == 127 {
				w = 32
			}
		}
		fmt.Fprintf(&out, "\t%d: %d,\n", c, w)
	}
	out.WriteString("}\n")
	formatted, err := format.Source(out.Bytes())
	check(err)
	check(os.WriteFile("collation_weights_gen.go", formatted, 0o644))
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
