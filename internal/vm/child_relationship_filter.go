// Child relationship negative filter
//
// A lazy org may not hold the catalog object that declares a child
// relationship, so a lookup that misses the installed objects used to complete
// the whole spread and look again. Most misses are not relationships at all (an
// unset field reaches the lookup too), and completing the spread for them costs
// hundreds of megabytes.
//
// The filter answers the miss without the spread. It holds a hash of every
// (parent, alias) pair that a complete shaped org answers for, taken over the
// feature signatures listed below, and the parent candidate keys the catalog
// definitions name. It can only be wrong in one direction that matters: a real
// pair missing from it. A pair that is present, or a hash collision, sends the
// lookup down the old path, which completes the spread. The filter applies only
// when every condition in childRelFilterApplies holds; anything else falls back.
//
// The data is generated by TestChildRelationshipFilterGenerate:
//
//	GLADE_UPDATE_CHILD_REL_FILTER=1 CGO_ENABLED=1 go test ./internal/vm -run TestChildRelationshipFilterGenerate -count=1 -timeout=0
//
// Rerun it after any change to the standard catalog, its feature policy or the
// relationship naming code. TestChildRelationshipFilterCoversEagerOrgs fails
// when the data is stale.

//go:embed child_relationship_filter.txt
var childRelFilterBlob []byte

// childRelFilterFeatureNames are the canonical capability names storage
// recognizes (canonicalFeatureName). TestChildRelationshipFilterFeatureListIsComplete
// keeps the list in step with that function.
var childRelFilterFeatureNames = []string{
	"PersonAccounts", "MultiCurrency", "Quotes", "OrderManagement", "OrderManagementEnabled",
	"B2BCommerce", "CommerceEnabled", "Territory2", "AccountTeams", "Forecasts", "OpportunityTeam",
	"OpportunitySplits", "OmniChannel", "Surveys", "CampaignInfluence2Enabled", "KnowledgeEnabled",
	"NetworksEnabled", "Sites", "Communities", "StateAndCountryPicklist", "ContactsToMultipleAccounts",
	"PlatformCache", "EnableSetPasswordInApi", "AddCustomApps", "AnalyticsAdminPerms", "HealthCloud",
	"LightningExperience", "Chatter", "Fundraising", "FundraisingEnabled", "DocGen", "PublicSectorAccess",
}

// childRelFilterShapeTokens are the internal shape markers that only add to a
// shape. The plain developer marker removes objects and is never covered.
var childRelFilterShapeTokens = []string{
	project.UnspecifiedStandardFieldShape,
	project.StandardFieldEditionDeveloper,
	project.StandardFieldEditionEnterprise,
	project.StandardFieldEditionOther,
}

var childRelFilterCovered = func() map[string]struct{} {
	covered := make(map[string]struct{}, len(childRelFilterFeatureNames)+len(childRelFilterShapeTokens))
	for _, name := range childRelFilterFeatureNames {
		covered[name] = struct{}{}
	}
	for _, name := range childRelFilterShapeTokens {
		covered[name] = struct{}{}
	}
	return covered
}()

const childRelFilterMagic = "glade-child-relationship-filter v2\n"

// childRelFilter is the decoded header of the data file. The hash tables stay
// in the embedded bytes and are searched in place.
type childRelFilter struct {
	pairs []byte // sorted hash lines, (parent, alias)
	keys  []byte // sorted hash lines, (parent candidate key, "")
}

func childRelFilterHash(parentKey, alias string) uint64 {
	const offset, prime = 14695981039346656037, 1099511628211
	h := uint64(offset)
	for i := 0; i < len(parentKey); i++ {
		h ^= uint64(parentKey[i])
		h *= prime
	}
	h *= prime // separator byte 0
	for i := 0; i < len(alias); i++ {
		h ^= uint64(alias[i])
		h *= prime
	}
	return h
}

// The data file is text so the leak scan can read it: a header, then two
// sorted tables with one line per hash, each hash truncated to 48 bits and
// written as 12 letters, one per nibble, from childRelFilterDigits. A truncated
// hash can only collide into a false positive, which falls back to the spread.
// Lines have a fixed width, so the tables are searched in place.
//
// The digits are sixteen consonants that are not hex digits (no vowels, no
// a-f, no 0-9), in ascending order so lines sort as their values do. A line
// holds no digit, no hex letter and no separator, so no hex-run, job id, ticket,
// path, mail or record id pattern can match it, and it is 12 characters, under
// the 15 a record id needs.
const (
	childRelFilterHashMask  = 1<<48 - 1
	childRelFilterLineWidth = 13
	childRelFilterDigits    = "ghjklmnpqrstvwxz"
)

func encodeChildRelFilter(stamp string, pairs, keys []uint64) []byte {
	var out bytes.Buffer
	out.WriteString(childRelFilterMagic)
	out.WriteString("stamp " + stamp + "\n")
	out.WriteString("pairs " + strconv.Itoa(len(pairs)) + "\n")
	out.WriteString("keys " + strconv.Itoa(len(keys)) + "\n")
	for _, table := range [][]uint64{pairs, keys} {
		for _, h := range table {
			h &= childRelFilterHashMask
			var line [childRelFilterLineWidth]byte
			for i := 11; i >= 0; i-- {
				line[i] = childRelFilterDigits[h&15]
				h >>= 4
			}
			line[12] = '\n'
			out.Write(line[:])
		}
	}
	return out.Bytes()
}

// decodeChildRelFilter returns nil when the blob is malformed or was generated
// from another catalog.
func decodeChildRelFilter(blob []byte, stamp string) *childRelFilter {
	rest, ok := bytes.CutPrefix(blob, []byte(childRelFilterMagic))
	if !ok {
		return nil
	}
	var counts [2]int
	for i, label := range []string{"stamp ", "pairs ", "keys "} {
		line, after, found := bytes.Cut(rest, []byte("\n"))
		if !found || !bytes.HasPrefix(line, []byte(label)) {
			return nil
		}
		value := string(line[len(label):])
		rest = after
		if i == 0 {
			if value != stamp || stamp == "" {
				return nil
			}
			continue
		}
		n, err := strconv.Atoi(value)
		if err != nil || n < 0 {
			return nil
		}
		counts[i-1] = n
	}
	if len(rest) != (counts[0]+counts[1])*childRelFilterLineWidth {
		return nil
	}
	split := counts[0] * childRelFilterLineWidth
	return &childRelFilter{pairs: rest[:split], keys: rest[split:]}
}

// childRelFilterDigitValue maps a digit letter to its value plus one; zero
// marks a byte that is not a digit.
var childRelFilterDigitValue = func() (table [256]uint8) {
	for i := 0; i < len(childRelFilterDigits); i++ {
		table[childRelFilterDigits[i]] = uint8(i + 1)
	}
	return table
}()

func childRelFilterLine(table []byte, i int) uint64 {
	var value uint64
	for _, c := range table[i*childRelFilterLineWidth : i*childRelFilterLineWidth+12] {
		d := childRelFilterDigitValue[c]
		if d == 0 {
			return 1<<63 - 1 // malformed: sorts last, matches nothing
		}
		value = value<<4 | uint64(d-1)
	}
	return value
}

func childRelFilterContains(table []byte, want uint64) bool {
	want &= childRelFilterHashMask
	lo, hi := 0, len(table)/childRelFilterLineWidth
	for lo < hi {
		mid := int(uint(lo+hi) >> 1)
		got := childRelFilterLine(table, mid)
		switch {
		case got == want:
			return true
		case got < want:
			lo = mid + 1
		default:
			hi = mid
		}
	}
	return false
}

var childRelFilterShared struct {
	once   sync.Once
	filter *childRelFilter
}

// childRelFilterOverride replaces the embedded data in tests.
var childRelFilterOverride *childRelFilter

func loadChildRelFilter() *childRelFilter {
	if childRelFilterOverride != nil {
		return childRelFilterOverride
	}
	childRelFilterShared.once.Do(func() {
		childRelFilterShared.filter = decodeChildRelFilter(childRelFilterBlob, storage.StandardCatalogStamp())
	})
	return childRelFilterShared.filter
}

// childRelFilterApplies reports whether the filter is a superset of what the
// org's complete spread would add. Every condition is fail closed.
//   - The spread is source backed and shaped. Only catalog objects are owed;
//     custom and project objects are installed already. The plain phase owes
//     objects the shape would remove.
//   - No namespace: the alias keys depend on it.
//   - Every feature is one the data covers. An unknown feature or the plain
//     developer marker is not.
//   - The data was generated from this catalog.
func childRelFilterApplies(org *storage.OrgState) *childRelFilter {
	if org == nil || org.StandardSpread != "shaped" || org.Namespace != "" {
		return nil
	}
	for _, feature := range org.Features {
		if _, ok := childRelFilterCovered[feature]; !ok {
			return nil
		}
	}
	return loadChildRelFilter()
}

// childRelFilterMissIsFinal reports whether no catalog object the lazy spread
// still owes can declare relationshipKey for parentObject, so a miss in the
// installed objects is the answer a complete org gives too.
func (vm *VM) childRelFilterMissIsFinal(parentObject, relationshipKey string) bool {
	filter := childRelFilterApplies(vm.Org)
	if filter == nil {
		return false
	}
	parentKey := strings.ToLower(strings.TrimSpace(parentObject))
	if parentKey == "" {
		return false
	}
	if canonical, ok := storage.ResolveKnownStandardObjectName(parentObject); ok && strings.EqualFold(canonical, strings.TrimSpace(parentObject)) {
		return !childRelFilterContains(filter.pairs, childRelFilterHash(parentKey, relationshipKey))
	}
	// Not a catalog name: an owed object can still reach it through a
	// namespace-stripped parent name. If no definition in the catalog names a
	// matching parent, no owed object contributes.
	for _, key := range jsonRelationshipParentCandidateKeys(parentObject) {
		if childRelFilterContains(filter.keys, childRelFilterHash(key, "")) {
			return false
		}
	}
	return true
}

// childRelFilterDeclinedKey marks, in the generation's lookup cache, a parent
// whose index was built without completing the spread.
func childRelFilterDeclinedKey(parentKey string) string {
	return "\x00childrel-filter\x00" + parentKey
}
