//go:build ignore

// gen_regex_name_age writes stdlib_regex_names_age.go: the code points that
// have a Unicode name in golang.org/x/text's Unicode 17.0 tables but none in
// its 15.0 tables. Java 21 knows Unicode 15.0, so \N{name} must not resolve
// these. It builds both table files as separate packages in a temporary
// module and compares them. Run it with: go generate ./internal/vm
package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

func main() {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "golang.org/x/text").Output()
	check(err)
	src := filepath.Join(strings.TrimSpace(string(out)), "unicode", "runenames")
	tmp, err := os.MkdirTemp("", "regexnameage")
	check(err)
	defer os.RemoveAll(tmp)
	build := regexp.MustCompile(`(?m)^//go:build.*\n`)
	for pkg, tables := range map[string]string{"p15": "tables15.0.0.go", "p17": "tables17.0.0.go"} {
		check(os.MkdirAll(filepath.Join(tmp, pkg), 0o755))
		for from, to := range map[string]string{"runenames.go": "runenames.go", tables: "tables.go"} {
			data, err := os.ReadFile(filepath.Join(src, from))
			check(err)
			text := strings.Replace(build.ReplaceAllString(string(data), ""), "package runenames", "package "+pkg, 1)
			check(os.WriteFile(filepath.Join(tmp, pkg, to), []byte(text), 0o644))
		}
	}
	check(os.WriteFile(filepath.Join(tmp, "go.mod"), []byte("module agecmp\ngo 1.22\n"), 0o644))
	check(os.WriteFile(filepath.Join(tmp, "main.go"), []byte(compare), 0o644))
	cmd := exec.Command("go", "run", ".")
	cmd.Dir = tmp
	ranges, err := cmd.Output()
	check(err)
	var b strings.Builder
	b.WriteString("// Code generated by gen_regex_name_age.go; DO NOT EDIT.\n\n")
	b.WriteString("package vm\n\n")
	b.WriteString("// javaNamesAfterUnicode15 lists the code points named in Unicode 17.0 but not in\n")
	b.WriteString("// 15.0, the version Java 21 carries. Source: golang.org/x/text runenames tables\n")
	b.WriteString("// 15.0.0 and 17.0.0, compared by gen_regex_name_age.go. For named characters this\n")
	b.WriteString("// equals the code points whose DerivedAge is later than 15.0.\n")
	b.WriteString("var javaNamesAfterUnicode15 = [][2]rune{\n")
	for _, line := range strings.Split(strings.TrimSpace(string(ranges)), "\n") {
		b.WriteString("\t" + line + "\n")
	}
	b.WriteString("}\n")
	check(os.WriteFile("stdlib_regex_names_age.go", []byte(b.String()), 0o644))
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

const compare = `package main

import (
	"fmt"

	"agecmp/p15"
	"agecmp/p17"
)

func main() {
	lo, prev := rune(-1), rune(0)
	for r := rune(0); r <= 0x10FFFF; r++ {
		if p15.Name(r) == "" && p17.Name(r) != "" {
			if lo < 0 {
				lo = r
			}
			prev = r
		} else if lo >= 0 {
			fmt.Printf("{0x%04X, 0x%04X},\n", lo, prev)
			lo = -1
		}
	}
	if lo >= 0 {
		fmt.Printf("{0x%04X, 0x%04X},\n", lo, prev)
	}
}
`
